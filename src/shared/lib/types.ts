export type Category = {
  _id: string;
  name: string;
  description: string;
  image: string;
  count?: number;
};
export type Variant = { id: string; label: string; price: number; stock: number; sku: string };
export type Product = {
  _id: string;
  slug: string;
  name: string;
  subtitle: string;
  description: string;
  category: string;
  image: string;
  origin: string;
  material: string;
  details: string[];
  care: string;
  variants: Variant[];
  featured: boolean;
  topPick?: boolean;
  newArrival?: boolean;
  gallery?: string[];
  active: boolean;
  rating: number;
  reviewCount: number;
  createdAt: string;
};
export type Address = {
  id?: string;
  name: string;
  phone: string;
  line1: string;
  line2: string;
  city: string;
  state: string;
  pincode: string;
};
export type User = {
  _id: string;
  name: string;
  email: string;
  passwordHash: string;
  sessionVersion?: number;
  role: 'customer' | 'admin';
  wishlist: string[];
  addresses: Address[];
  createdAt: string;
};
export type PublicUser = Omit<User, 'passwordHash'>;
export type CartLine = { productId: string; variantId: string; quantity: number };
export type OrderItem = CartLine & {
  name: string;
  variantLabel: string;
  price: number;
  image: string;
  slug: string;
};
export type OrderStatus = 'confirmed' | 'processing' | 'shipped' | 'delivered' | 'cancelled';
export type Order = {
  _id: string;
  userId: string;
  email: string;
  items: OrderItem[];
  address: Address;
  subtotal: number;
  shipping: number;
  discount: number;
  total: number;
  coupon: string;
  paymentMethod: 'cod' | 'demo' | 'upi' | 'card';
  providerOrderId?: string;
  paymentId?: string;
  shipment?: {
    mode: string;
    shipmentId: string;
    providerOrderId?: string;
    awb: string;
    courier: string;
    status: string;
    labelUrl?: string;
    trackingUrl?: string;
    bookedAt: string;
  };
  paymentStatus: string;
  status: OrderStatus;
  history: { status: string; note: string; at: string }[];
  tracking: string;
  returnRequest?: { reason: string; at: string; status: string };
  createdAt: string;
  idempotencyKey?: string;
};
export type Review = {
  _id: string;
  userId: string;
  productId: string;
  name: string;
  rating: number;
  title: string;
  body: string;
  approved: boolean;
  verified: boolean;
  createdAt: string;
};
export type Coupon = {
  _id: string;
  code: string;
  type: 'percent' | 'fixed';
  value: number;
  minOrder: number;
  maxDiscount: number;
  active: boolean;
  expiresAt: string;
};
export type Settings = {
  _id: string;
  storeName: string;
  supportEmail: string;
  phone: string;
  freeShippingAt: number;
  shippingFee: number;
  codEnabled: boolean;
  announcement: string;
};
